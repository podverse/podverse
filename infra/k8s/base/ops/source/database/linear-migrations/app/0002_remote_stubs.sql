-- Remote stubs: minimal placeholder rows for podcast:remoteItem feeds and items that the index
-- provider resolved but Podverse has not fully parsed. Stubs never write a feed, channel, or item
-- row, so browse, search, sitemaps, and scheduled parses never see them.

--
-- Name: remote_channel_stub; Type: TABLE; Schema: public; Owner: -
--

CREATE TABLE public.remote_channel_stub (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    index_provider text NOT NULL,
    provider_feed_id public.varchar_short NOT NULL,
    feed_guid uuid,
    feed_url public.varchar_url NOT NULL,
    title public.varchar_normal,
    author public.varchar_normal,
    image_url public.varchar_uri,
    medium_id integer,
    resolved_at timestamp with time zone DEFAULT now() NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT remote_channel_stub_pkey PRIMARY KEY (id),
    CONSTRAINT remote_channel_stub_provider_feed_key UNIQUE (index_provider, provider_feed_id),
    CONSTRAINT remote_channel_stub_index_provider_check CHECK ((index_provider = ANY (ARRAY['podcast_index'::text]))),
    CONSTRAINT remote_channel_stub_medium_id_fkey FOREIGN KEY (medium_id) REFERENCES public.medium(id)
);

CREATE INDEX idx_remote_channel_stub_feed_guid ON public.remote_channel_stub USING btree (feed_guid);

CREATE INDEX idx_remote_channel_stub_feed_url ON public.remote_channel_stub USING btree (feed_url);

CREATE TRIGGER set_updated_at_remote_channel_stub BEFORE UPDATE ON public.remote_channel_stub FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_field();

--
-- Name: remote_channel_stub_alias; Type: TABLE; Schema: public; Owner: -
-- Every normalized reference key that resolved to a stub, so a reference whose GUID or URL differs
-- from the provider's canonical values still finds its stub.
--

CREATE TABLE public.remote_channel_stub_alias (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    remote_channel_stub_id integer NOT NULL,
    key_kind text NOT NULL,
    key_value public.varchar_uri NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT remote_channel_stub_alias_pkey PRIMARY KEY (id),
    CONSTRAINT remote_channel_stub_alias_key_kind_key_value_key UNIQUE (key_kind, key_value),
    CONSTRAINT remote_channel_stub_alias_key_kind_check CHECK ((key_kind = ANY (ARRAY['feed_guid'::text, 'feed_url'::text]))),
    CONSTRAINT remote_channel_stub_alias_remote_channel_stub_id_fkey FOREIGN KEY (remote_channel_stub_id) REFERENCES public.remote_channel_stub(id) ON DELETE CASCADE
);

CREATE INDEX idx_remote_channel_stub_alias_remote_channel_stub_id ON public.remote_channel_stub_alias USING btree (remote_channel_stub_id);

--
-- Name: remote_item_stub; Type: TABLE; Schema: public; Owner: -
-- An item stub always belongs to a channel stub.
--

CREATE TABLE public.remote_item_stub (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    remote_channel_stub_id integer NOT NULL,
    item_guid public.varchar_uri NOT NULL,
    provider_item_id public.varchar_short,
    title public.varchar_normal,
    image_url public.varchar_uri,
    pub_date timestamp with time zone,
    duration_seconds integer,
    resolved_at timestamp with time zone DEFAULT now() NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT remote_item_stub_pkey PRIMARY KEY (id),
    CONSTRAINT remote_item_stub_channel_item_guid_key UNIQUE (remote_channel_stub_id, item_guid),
    CONSTRAINT remote_item_stub_duration_seconds_check CHECK (((duration_seconds IS NULL) OR (duration_seconds > 0))),
    CONSTRAINT remote_item_stub_remote_channel_stub_id_fkey FOREIGN KEY (remote_channel_stub_id) REFERENCES public.remote_channel_stub(id) ON DELETE CASCADE
);

CREATE TRIGGER set_updated_at_remote_item_stub BEFORE UPDATE ON public.remote_item_stub FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_field();
